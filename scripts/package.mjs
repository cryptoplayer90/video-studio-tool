import { mkdir, cp, rm, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
await import('./build.mjs');
const root=fileURLToPath(new URL('../',import.meta.url));
const {version}=JSON.parse(await readFile(root+'package.json','utf8'));
const folder=`video-studio-${version}`;
await mkdir(root+'release',{recursive:true});
await rm(root+'release/'+folder,{recursive:true,force:true});
await mkdir(root+'release/'+folder);
await cp(root+'dist/index.html',root+'release/'+folder+'/index.html');
for(const name of ['README.md','LICENSE','THIRD_PARTY_NOTICES.md','provider-config.example.json','examples'])await cp(root+name,root+'release/'+folder+'/'+name,{recursive:true});
const archive=`${folder}.zip`;
await rm(root+'release/'+archive,{force:true});
execFileSync('python3',['-c','import shutil,sys; shutil.make_archive(sys.argv[1], "zip", sys.argv[2], sys.argv[3])',root+'release/'+folder,root+'release',folder],{stdio:'inherit'});
console.log(`Ready: release/${archive}`);
const sourceFolder=`video-studio-${version}-source`;
await rm(root+'release/'+sourceFolder,{recursive:true,force:true});
await mkdir(root+'release/'+sourceFolder);
for(const name of ['src','scripts','tests','examples','README.md','LICENSE','THIRD_PARTY_NOTICES.md','provider-config.example.json','package.json','package-lock.json','.gitignore']) await cp(root+name,root+'release/'+sourceFolder+'/'+name,{recursive:true});
execFileSync('python3',['-c','import shutil,sys; shutil.make_archive(sys.argv[1], "zip", sys.argv[2], sys.argv[3])',root+'release/'+sourceFolder,root+'release',sourceFolder],{stdio:'inherit'});
console.log(`Ready: release/${sourceFolder}.zip`);
